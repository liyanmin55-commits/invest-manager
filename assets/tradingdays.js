// 交易日历：内置 2025–2026 中国 A股 休市/开市日（法定节假日 + 调休补班）。
// 数据依据：国务院办公厅《关于2025年部分节假日安排的通知》(2024-11-12)、
//          《关于2026年部分节假日安排的通知》(2025-11-04)。
// 2027 及以后尚未公布，超出 KNOWN_END 时仅按周末判断（节假日不判，待每年补充）。
// 用法（全局 TradingDays）：
//   TradingDays.isTradingDay(date)            // 该 Date 是否交易日
//   TradingDays.nextTradingDay(from, true)   // from 起(含当天)下一个交易日
//   TradingDays.ymd(date)                    // Date -> "YYYY-MM-DD"
const TradingDays = (() => {
  // 休市日（法定节假日放假日，含调休假期，YYYY-MM-DD）
  const HOLIDAYS = new Set([
    // ===== 2025 =====
    "2025-01-01",
    "2025-01-28", "2025-01-29", "2025-01-30", "2025-01-31", "2025-02-01", "2025-02-02", "2025-02-03", "2025-02-04",
    "2025-04-04", "2025-04-05", "2025-04-06",
    "2025-05-01", "2025-05-02", "2025-05-03", "2025-05-04", "2025-05-05",
    "2025-05-31", "2025-06-01", "2025-06-02",
    "2025-10-01", "2025-10-02", "2025-10-03", "2025-10-04", "2025-10-05", "2025-10-06", "2025-10-07", "2025-10-08",
    // ===== 2026 =====
    "2026-01-01", "2026-01-02", "2026-01-03",
    "2026-02-15", "2026-02-16", "2026-02-17", "2026-02-18", "2026-02-19", "2026-02-20", "2026-02-21", "2026-02-22", "2026-02-23",
    "2026-04-04", "2026-04-05", "2026-04-06",
    "2026-05-01", "2026-05-02", "2026-05-03", "2026-05-04", "2026-05-05",
    "2026-06-19", "2026-06-20", "2026-06-21",
    "2026-09-25", "2026-09-26", "2026-09-27",
    "2026-10-01", "2026-10-02", "2026-10-03", "2026-10-04", "2026-10-05", "2026-10-06", "2026-10-07",
  ]);
  // 补班开市日（周末上班，休市例外开放）
  const EXTRA = new Set([
    "2025-01-26", "2025-02-08", "2025-04-27", "2025-09-28", "2025-10-11",
    "2026-01-04", "2026-02-14", "2026-02-28", "2026-05-09", "2026-09-20", "2026-10-10",
  ]);
  const KNOWN_END = new Date(2026, 11, 31); // 已知节假日数据覆盖到 2026-12-31

  function ymd(d) {
    return d.getFullYear() + "-" + String(d.getMonth() + 1).padStart(2, "0") + "-" + String(d.getDate()).padStart(2, "0");
  }
  function addDays(d, n) { const x = new Date(d); x.setDate(x.getDate() + n); return x; }

  // 是否交易日：周末仅补班日开市；工作日超已知范围只排周末，在范围内再排法定节假日
  function isTradingDay(d) {
    const dow = d.getDay(); // 0=周日 .. 6=周六
    const key = ymd(d);
    if (dow === 0 || dow === 6) return EXTRA.has(key);
    if (d <= KNOWN_END && HOLIDAYS.has(key)) return false;
    return true;
  }
  // 从 from 起找下一交易日（inclusive=true 含 from 当天）
  function nextTradingDay(from, inclusive) {
    let d = new Date(from);
    if (!inclusive) d = addDays(d, 1);
    let guard = 0;
    while (!isTradingDay(d)) {
      d = addDays(d, 1);
      if (++guard > 30) break; // 极端兜底，避免死循环
    }
    return d;
  }

  return { isTradingDay, nextTradingDay, ymd, addDays, HOLIDAYS, EXTRA };
})();
